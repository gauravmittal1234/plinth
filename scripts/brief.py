#!/usr/bin/env python3
"""Build a compact task brief so an agent reads 1-2 pages instead of the whole doc set.

Usage: python3 scripts/brief.py T23 [T24 ...]   -> docs/engineering/briefs/T23.md
Pulls: the task's section from WORK_BREAKDOWN.md, every INTEGRATION_NOTES.md line that
names the task, and the visible copy of each artboard the task cites (via artboard_text.py).
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WB = (ROOT / "docs/engineering/WORK_BREAKDOWN.md").read_text()
NOTES = (ROOT / "docs/engineering/INTEGRATION_NOTES.md").read_text()
OUT = ROOT / "docs/engineering/briefs"

RULES = """## Budget rules (read first)
- Read THIS brief, AGENTS.md, and only the source files you edit or import. Open DESIGN.md / API_CONTRACTS.md
  / DATA_MODEL.md only for a specific section this brief names.
- Quiet output: run tests with failures-only reporters and pipe long output through `tail -40`.
- Run only the affected workspace's tests locally; CI runs the full suite.
- Max 3 attempts on any one failure, then stop and report the blocker with the error lines.
- No screenshots or browser sessions unless you are fixing a visual bug.
- Commit in small steps. When acceptance passes locally: push, open the PR against `main`, and STOP.
  Do not wait for or poll CI; the lead watches CI and sends back failures.
"""

def section(tid: str) -> str:
    m = re.search(rf"^#### {re.escape(tid)} .*?(?=^#### |^### |\Z)", WB, re.S | re.M)
    return m.group(0).strip() if m else f"(No section for {tid} in WORK_BREAKDOWN.md)"

def notes(tid: str) -> str:
    keep = [l for l in NOTES.splitlines() if re.search(rf"\b{re.escape(tid)}\b", l)]
    return "\n".join(keep) or "(none)"

def artboards(text: str) -> str:
    names = sorted(set(re.findall(r"\b((?:Web|App|Wa)[A-Z][A-Za-z]+)\.dc\.html", text)))
    out = []
    for n in names:
        p = ROOT / "product/design/artboards" / f"{n}.dc.html"
        if not p.exists():
            continue
        r = subprocess.run([sys.executable, str(ROOT / "scripts/artboard_text.py"), str(p)],
                           capture_output=True, text=True)
        txt = r.stdout.strip()
        if len(txt) > 12000:
            txt = txt[:12000] + "\n… (truncated; open the artboard for the rest)"
        out.append(f"### {n}\n```text\n{txt}\n```")
    return "\n\n".join(out) or "(no artboards cited)"

def main(ids):
    OUT.mkdir(parents=True, exist_ok=True)
    for tid in ids:
        sec = section(tid)
        body = (f"# Brief {tid}\n\nGenerated by scripts/brief.py. Base branch: `main`. PR target: `main`.\n\n"
                f"{RULES}\n## Task (from WORK_BREAKDOWN.md)\n\n{sec}\n\n"
                f"## Handoffs and decisions that mention {tid} (INTEGRATION_NOTES.md)\n\n{notes(tid)}\n\n"
                f"## Artboard copy (layout copy comes from here; facts from DESIGN.md §5b)\n\n{artboards(sec)}\n")
        (OUT / f"{tid}.md").write_text(body)
        print(f"{tid}: {len(body.split())} words")

if __name__ == "__main__":
    main(sys.argv[1:])
