const FORMATS = {
  "plinth/css": formatCss,
  "plinth/tailwind": formatTailwind,
  "plinth/ts": formatTs,
  "plinth/dart-values": formatDartValues,
  "plinth/dart-flutter": formatDartFlutter,
};

export async function build({
  distDir = join(PKG, "dist"),
  dartDir = join(PKG, "dart", "lib"),
} = {}) {
  for (const [name, format] of Object.entries(FORMATS))
    StyleDictionary.registerFormat({ name, format });
  const slash = (d) => (d.endsWith("/") ? d : `${d}/`);
  const sd = new StyleDictionary({
    source: [join(PKG, "tokens.json")],
    usesDtcg: true,
    log: { warnings: "error", verbosity: "silent" },
    platforms: {
      web: {
        transforms: ["name/kebab"],
        buildPath: slash(distDir),
        files: [
          { destination: "tokens.css", format: "plinth/css" },
          { destination: "theme.css", format: "plinth/tailwind" },
          { destination: "tokens.ts", format: "plinth/ts" },
        ],
      },
      dart: {
        transforms: ["name/kebab"],
        buildPath: slash(dartDir),
        files: [
          { destination: "plinth_token_values.dart", format: "plinth/dart-values" },
          { destination: "plinth_tokens.dart", format: "plinth/dart-flutter" },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > -1 ? resolve(process.argv[i + 1]) : undefined;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await build({ distDir: arg("--dist"), dartDir: arg("--dart") });
  console.log("@plinth/tokens: built dist/ and dart/lib/ from tokens.json");
}
