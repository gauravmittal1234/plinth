const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const THEMES = ["day", "night"];
const RISK_KEYS = ["low", "moderate", "elevated", "high", "severe", "limited", "notScored"];
const RISK_ROLES = ["ink", "fill", "text"];
const GENERIC_FAMILIES = new Set(["system-ui", "sans-serif", "serif", "monospace", "cursive"]);
const HEADER = "Generated by @plinth/tokens (scripts/build.mjs) from tokens.json. Do not edit.";

// ---------------------------------------------------------------- helpers

const kebab = (s) =>
  String(s)
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
const pascal = (s) => String(s).charAt(0).toUpperCase() + String(s).slice(1);

function unit(value, suffix) {
  const s = String(value);
  if (!s.endsWith(suffix)) throw new Error(`expected a ${suffix} value, got "${s}"`);
  const n = Number(s.slice(0, -suffix.length));
  if (!Number.isFinite(n)) throw new Error(`not a number: "${s}"`);
  return n;
}
const px = (v) => unit(v, "px");
const ms = (v) => unit(v, "ms");
const em = (v) => unit(v, "em");

/** "#RRGGBB" | "transparent" | "rgba(r, g, b, a)" → {r, g, b, a}. */
export function parseColor(value) {
  const s = String(value).trim();
  let m = /^#([0-9A-Fa-f]{6})$/.exec(s);
  if (m) {
    const n = parseInt(m[1], 16);
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: 1 };
  }
  if (s === "transparent") return { r: 0, g: 0, b: 0, a: 0 };
  m = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(0|1|0?\.\d+)\s*\)$/.exec(s);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: +m[4] };
  throw new Error(`unsupported colour "${s}" (use #RRGGBB, transparent or rgba())`);
}

const hex2 = (n) => n.toString(16).toUpperCase().padStart(2, "0");

function cssColor(value) {
  const c = parseColor(value);
  if (c.a === 1) return `#${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`;
  if (c.a === 0) return "transparent";
  return `rgba(${c.r}, ${c.g}, ${c.b}, ${c.a})`;
}

/** 0xAARRGGBB, alpha rounded to 8 bits (the same rounding the parity test uses). */
function argb(value) {
  const c = parseColor(value);
  return `0x${hex2(Math.round(c.a * 255))}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`;
}

const cssFamily = (stack) => stack.map((f) => (GENERIC_FAMILIES.has(f) ? f : `"${f}"`)).join(", ");
const pxToRem = (s) => String(s).replace(/(\d+(?:\.\d+)?)px/g, (_, n) => `${+n / 16}rem`);
const cssLength = (v) => (px(v) === 0 ? "0" : `${px(v)}px`);
const cssShadow = (s) =>
  `${cssLength(s.offsetX)} ${cssLength(s.offsetY)} ${cssLength(s.blur)} ${cssLength(s.spread)} ${cssColor(s.color)}`;
const cssBezier = (b) => `cubic-bezier(${b.join(", ")})`;
const num = (n) => String(n);

/** One line if it fits in 80 columns, else one item per line (what `dart format` does). */
function dartList(indent, head, items, tail) {
  const one = `${indent}${head}${items.join(", ")}${tail}`;
  if (one.length <= 80) return [one];
  return [
    `${indent}${head}`,
    ...items.map((i) => `${indent}  ${i},`),
    `${indent}${tail.trimStart()}`,
  ];
}

// ---------------------------------------------------------------- model

/** Style Dictionary's resolved token tree → plain values (skipping $-metadata). */
function plain(node) {
  if (node && typeof node === "object" && "$value" in node) return node.$value;
  const out = {};
  for (const [k, v] of Object.entries(node)) if (!k.startsWith("$")) out[k] = plain(v);
  return out;
}

function fontSizeOf(v) {
  const s = String(v);
  const m = /^clamp\(\s*([\d.]+)px\s*,\s*([^,]+?)\s*,\s*([\d.]+)px\s*\)$/.exec(s);
  if (m) return { size: +m[3], sizeMin: +m[1], sizeFluid: m[2] };
  return { size: px(s) };
}

function model(dictionary) {
  const t = plain(dictionary.tokens);
  const version = dictionary.tokens.$extensions?.["in.plinth"]?.version ?? "0.0.0";
  for (const theme of THEMES) {
    if (!t.color[theme] || !t.risk[theme] || !t.elevation[theme])
      throw new Error(`theme "${theme}" is missing colour, risk or elevation tokens`);
  }
  const colorNames = Object.keys(t.color.day);
  const nightNames = Object.keys(t.color.night);
  if (colorNames.join() !== nightNames.join())
    throw new Error("color.day and color.night must define the same names in the same order");
  for (const theme of THEMES)
    for (const k of RISK_KEYS)
      for (const r of RISK_ROLES)
        if (t.risk[theme]?.[k]?.[r] === undefined)
          throw new Error(`risk.${theme}.${k}.${r} is missing`);

  const typeRole = (v, family) => ({
    family,
    weight: v.fontWeight,
    ...fontSizeOf(v.fontSize),
    cssSize: pxToRem(v.fontSize),
    lineHeight: v.lineHeight,
    letterSpacing: em(v.letterSpacing),
  });
  const familyOf = (stack) =>
    stack.join() === t.font.family.display.join()
      ? "display"
      : stack.join() === t.font.family.text.join()
        ? "text"
        : (() => {
            throw new Error(`typography uses an unknown family stack: ${stack.join()}`);
          })();
  const type = {};
  for (const platform of ["web", "app"]) {
    type[platform] = {};
    for (const [role, v] of Object.entries(t.type[platform]))
      type[platform][role] = typeRole(v, familyOf(v.fontFamily));
  }
  const mapValues = (obj, fn) =>
    Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, fn(v, k)]));
  const dim = (v) => (typeof v === "string" && v.endsWith("px") ? px(v) : v);

  return {
    version,
    colorNames,
    color: t.color,
    risk: t.risk,
    elevation: mapValues(t.elevation, (themeVals) =>
      mapValues(themeVals, (s) => ({
        color: s.color,
        offsetX: px(s.offsetX),
        offsetY: px(s.offsetY),
        blur: px(s.blur),
        spread: px(s.spread),
        css: cssShadow(s),
      })),
    ),
    font: t.font,
    type,
    space: mapValues(t.space, px),
    layout: mapValues(t.layout, dim),
    radius: mapValues(t.radius, dim),
    motion: {
      ease: t.motion.ease,
      duration: mapValues(t.motion.duration, ms),
      stagger: mapValues(t.motion.stagger, ms),
      distance: mapValues(t.motion.distance, px),
      scale: t.motion.scale,
    },
    pattern: { hatch: mapValues(t.pattern.hatch, dim) },
    component: mapValues(t.component, (group) => mapValues(group, dim)),
  };
}

// ---------------------------------------------------------------- CSS

/** Every CSS custom property, as {path, name, value}; themed ones per theme. */
function cssEntries(m) {
  const themed = {};
  for (const theme of THEMES) {
    const list = [];
    for (const k of m.colorNames)
      list.push({
        path: ["color", k],
        name: `--pl-color-${kebab(k)}`,
        value: cssColor(m.color[theme][k]),
      });
    for (const k of RISK_KEYS)
      for (const r of RISK_ROLES)
        list.push({
          path: ["risk", k, r],
          name: `--pl-risk-${kebab(k)}-${r}`,
          value: cssColor(m.risk[theme][k][r]),
        });
    for (const [k, s] of Object.entries(m.elevation[theme]))
      list.push({ path: ["elevation", k], name: `--pl-elevation-${kebab(k)}`, value: s.css });
    themed[theme] = list;
  }

  const fixed = [];
  const add = (path, value) =>
    fixed.push({ path, name: `--pl-${path.map(kebab).join("-")}`, value: String(value) });
  for (const [k, stack] of Object.entries(m.font.family))
    add(["font", "family", k], cssFamily(stack));
  for (const [k, w] of Object.entries(m.font.weight)) add(["font", "weight", k], w);
  add(["font", "numeric"], m.font.numeric);
  for (const [role, r] of Object.entries(m.type.web)) {
    add(["type", role, "family"], `var(--pl-font-family-${r.family})`);
    add(["type", role, "weight"], r.weight);
    add(["type", role, "size"], r.cssSize);
    add(["type", role, "lineHeight"], num(r.lineHeight));
    add(["type", role, "letterSpacing"], r.letterSpacing === 0 ? "0" : `${r.letterSpacing}em`);
  }
  for (const [k, v] of Object.entries(m.space)) add(["space", k], `${v}px`);
  for (const [k, v] of Object.entries(m.layout))
    add(["layout", k], typeof v === "number" ? `${v}px` : v);
  for (const [k, v] of Object.entries(m.radius))
    add(["radius", k], typeof v === "number" ? `${v}px` : v);
  for (const [k, v] of Object.entries(m.motion.ease)) add(["motion", "ease", k], cssBezier(v));
  for (const [k, v] of Object.entries(m.motion.duration)) add(["motion", "duration", k], `${v}ms`);
  for (const [k, v] of Object.entries(m.motion.stagger)) add(["motion", "stagger", k], `${v}ms`);
  for (const [k, v] of Object.entries(m.motion.distance)) add(["motion", "distance", k], `${v}px`);
  for (const [k, v] of Object.entries(m.motion.scale)) add(["motion", "scale", k], num(v));
  add(["pattern", "hatch", "angle"], `${m.pattern.hatch.angle}deg`);
  add(["pattern", "hatch", "stroke"], `${m.pattern.hatch.stroke}px`);
  add(["pattern", "hatch", "period"], `${m.pattern.hatch.period}px`);
  for (const [group, vals] of Object.entries(m.component))
    for (const [k, v] of Object.entries(vals)) {
      const isCount = ["columns", "rows"].includes(k) || k.endsWith("Weight");
      add(["component", group, k], isCount ? v : `${v}px`);
    }
  return { themed, fixed };
}

function formatCss({ dictionary }) {
  const m = model(dictionary);
  const { themed, fixed } = cssEntries(m);
  const block = (selector, scheme, list) =>
    [
      `${selector} {`,
      `  color-scheme: ${scheme};`,
      ...list.map((e) => `  ${e.name}: ${e.value};`),
      "}",
    ].join("\n");
  const reduced = fixed.filter(
    (e) =>
      e.path[0] === "motion" &&
      (e.path[1] === "duration" ||
        e.path[1] === "stagger" ||
        e.path[1] === "distance" ||
        (e.path[1] === "scale" && e.path[2] === "drift")),
  );
  const reducedValue = (e) =>
    e.path[1] === "distance" ? "0px" : e.path[1] === "scale" ? "1" : "0ms";
  return (
    [
      `/* ${HEADER} */`,
      `/* Plinth tokens v${m.version}. Day is the default; set data-theme="night" on <html> (or any`,
      `   subtree) for Night. No glass, glow or resting shadows (DESIGN.md §0): the only translucent`,
      `   values are --pl-color-scrim and --pl-elevation-sheet. */`,
      "",
      block(':root,\n[data-theme="day"]', "light", themed.day),
      "",
      block('[data-theme="night"]', "dark", themed.night),
      "",
      [":root {", ...fixed.map((e) => `  ${e.name}: ${e.value};`), "}"].join("\n"),
      "",
      "/* Reduced motion: every animation lands on its final state at once. */",
      "@media (prefers-reduced-motion: reduce) {",
      "  :root {",
      ...reduced.map((e) => `    ${e.name}: ${reducedValue(e)};`),
      "  }",
      "}",
    ].join("\n") + "\n"
  );
}

function formatTailwind({ dictionary }) {
  const m = model(dictionary);
  const { themed, fixed } = cssEntries(m);
  const lines = [];
  const reset = (ns, why) => lines.push(`  --${ns}-*: initial; /* ${why} */`);
  const map = (name, cssVarName) => lines.push(`  --${name}: var(${cssVarName});`);

  reset("color", "only Plinth colours: no default palette, no hard-coded colours");
  for (const e of themed.day.filter((x) => x.path[0] === "color"))
    map(`color-${kebab(e.path[1])}`, e.name);
  for (const e of themed.day.filter((x) => x.path[0] === "risk"))
    map(`color-risk-${kebab(e.path[1])}-${e.path[2]}`, e.name);
  lines.push("");
  reset("font", "Bricolage Grotesque (display) and Mukta (sans)");
  map("font-display", "--pl-font-family-display");
  map("font-sans", "--pl-font-family-text");
  reset("font-weight", "only the weights the two families ship");
  for (const k of Object.keys(m.font.weight))
    map(`font-weight-${kebab(k)}`, `--pl-font-weight-${kebab(k)}`);
  lines.push("");
  reset("text", "the type roles: five sizes on a page at most");
  for (const role of Object.keys(m.type.web)) {
    const v = (p) => `--pl-type-${kebab(role)}-${p}`;
    map(`text-${kebab(role)}`, v("size"));
    map(`text-${kebab(role)}--line-height`, v("line-height"));
    map(`text-${kebab(role)}--letter-spacing`, v("letter-spacing"));
    map(`text-${kebab(role)}--font-weight`, v("weight"));
  }
  lines.push("");
  lines.push("  --spacing: 4px; /* 4-px steps: p-1 = 4px … p-18 = 72px */");
  map("container-content", "--pl-layout-content-max");
  map("container-measure", "--pl-layout-measure");
  lines.push("");
  reset("radius", "square media, panels ≤ 8 px, pills");
  for (const e of fixed.filter((x) => x.path[0] === "radius"))
    map(`radius-${kebab(e.path[1])}`, e.name);
  lines.push("");
  reset("shadow", "no shadows at rest");
  for (const k of Object.keys(m.elevation.day))
    map(`shadow-${kebab(k)}`, `--pl-elevation-${kebab(k)}`);
  reset("inset-shadow", "no shadows at rest");
  reset("drop-shadow", "no shadows at rest");
  reset("text-shadow", "no glow on text");
  reset("blur", "no glass: no blur or backdrop-blur utilities");
  lines.push("");
  reset("ease", "the motion curves");
  for (const k of Object.keys(m.motion.ease))
    map(`ease-${kebab(k)}`, `--pl-motion-ease-${kebab(k)}`);

  return (
    [
      `/* ${HEADER} */`,
      "/* Tailwind CSS v4 theme for Plinth. In the app's global CSS:",
      '     @import "tailwindcss";',
      '     @import "@plinth/tokens/theme.css";',
      "   Utilities read the runtime custom properties, so data-theme switches Day/Night. */",
      '@import "./tokens.css";',
      "",
      "@theme inline {",
      ...lines,
      "}",
    ].join("\n") + "\n"
  );
}

// ---------------------------------------------------------------- TypeScript

function formatTs({ dictionary }) {
  const m = model(dictionary);
  const { themed, fixed } = cssEntries(m);
  const json = (v) => JSON.stringify(v, null, 2);

  const color = Object.fromEntries(
    THEMES.map((th) => [
      th,
      Object.fromEntries(m.colorNames.map((k) => [k, cssColor(m.color[th][k])])),
    ]),
  );
  const risk = {
    band: m.risk.band,
    ...Object.fromEntries(
      THEMES.map((th) => [
        th,
        Object.fromEntries(
          RISK_KEYS.map((k) => [
            k,
            Object.fromEntries(RISK_ROLES.map((r) => [r, cssColor(m.risk[th][k][r])])),
          ]),
        ),
      ]),
    ),
  };
  const elevation = Object.fromEntries(
    THEMES.map((th) => [
      th,
      Object.fromEntries(
        Object.entries(m.elevation[th]).map(([k, s]) => [k, { ...s, color: cssColor(s.color) }]),
      ),
    ]),
  );
  const font = {
    family: Object.fromEntries(
      Object.entries(m.font.family).map(([k, stack]) => [
        k,
        { name: stack[0], stack: cssFamily(stack) },
      ]),
    ),
    weight: m.font.weight,
    numeric: m.font.numeric,
  };
  const type = Object.fromEntries(
    Object.entries(m.type).map(([platform, roles]) => [
      platform,
      Object.fromEntries(
        Object.entries(roles).map(([role, r]) => [
          role,
          Object.fromEntries(Object.entries(r).filter(([k]) => k !== "cssSize")),
        ]),
      ),
    ]),
  );

  const cssVar = {};
  const setPath = (obj, path, value) => {
    let o = obj;
    for (const p of path.slice(0, -1)) o = o[p] ??= {};
    o[path[path.length - 1]] = value;
  };
  for (const e of [...themed.day, ...fixed]) setPath(cssVar, e.path, `var(${e.name})`);

  const out = [
    `// ${HEADER}`,
    "// Values are px (numbers), ms (durations), em (letterSpacing) and CSS colour strings.",
    "",
    `export const tokensVersion = ${json(m.version)};`,
    "",
    `export const themes = ${json(THEMES)} as const;`,
    "export type Theme = (typeof themes)[number];",
    "",
    `export const riskKeys = ${json(RISK_KEYS)} as const;`,
    "export type RiskKey = (typeof riskKeys)[number];",
    `export const riskBands = ${json(RISK_KEYS.slice(0, 5))} as const;`,
    "export type RiskBand = (typeof riskBands)[number];",
    'export type MeterStyle = "solid" | "dashed" | "outlined";',
    "",
    "/** Theme colours (DESIGN §3.1, §3.2b, §0). */",
    `export const color = ${json(color)} as const;`,
    'export type ColorName = keyof (typeof color)["day"];',
    "",
    "/** Delivery-risk ramp (DESIGN §3.2). Band names and frequencies are server copy, not tokens. */",
    `export const risk = ${json(risk)} as const;`,
    "",
    "/** Shadows for floating surfaces only (sheet, menu, dialog, drawer). */",
    `export const elevation = ${json(elevation)} as const;`,
    "",
    `export const font = ${json(font)} as const;`,
    "",
    "/** Type roles: size in px (fluid roles also carry sizeMin and sizeFluid), letterSpacing in em. */",
    `export const typography = ${json(type)} as const;`,
    "",
    `export const space = ${json(m.space)} as const;`,
    "",
    `export const layout = ${json(m.layout)} as const;`,
    "",
    `export const radius = ${json(m.radius)} as const;`,
    "",
    `export const motion = ${json(m.motion)} as const;`,
    "",
    `export const pattern = ${json(m.pattern)} as const;`,
    "",
    `export const component = ${json(m.component)} as const;`,
    "",
    "/** `var(--pl-…)` references for inline styles and SVG; they follow data-theme. */",
    `export const cssVar = ${json(cssVar)} as const;`,
  ];
  return out.join("\n") + "\n";
}

