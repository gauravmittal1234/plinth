#!/usr/bin/env node
// Builds supabase/seed/*.sql from packages/fixtures/canonical/*.json through the seedmaps.
//
//   node scripts/build-seed.mjs            # write supabase/seed (honours `requires`)
//   node scripts/build-seed.mjs --check    # exit 1 if supabase/seed would change
//   node scripts/build-seed.mjs --all --out <dir>   # preview every seedmap, ignoring `requires`
//
// A seedmap (seedmap/<name>.mjs) exports { output, requires, build(ctx) }. `requires` lists
// markers; each must appear in a file name under supabase/migrations (a task's migration
// prefix such as "20261020", or a marker such as "m2_people"). When one is missing the seedmap
// is skipped and its output file holds only a header saying why, so `supabase db reset`
// never inserts into tables that do not exist yet. Output is deterministic: no timestamps.
// Owner: T03 (T03b adds seedmaps). Never hand-edit supabase/seed.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const ROOT = resolve(PKG, "../..");
const MIGRATIONS = join(ROOT, "supabase", "migrations");
const SEED_DIR = join(ROOT, "supabase", "seed");

// ---- SQL literal helpers handed to seedmaps
const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`non-finite number ${v}`);
    return String(v);
  }
  return `'${String(v).replace(/'/g, "''")}'`;
};
export const sql = {
  q,
  jsonb: (v) => (v === null || v === undefined ? "null" : `${q(JSON.stringify(v))}::jsonb`),
  uuids: (a) => (a && a.length ? `array[${a.map(q).join(", ")}]::uuid[]` : "'{}'::uuid[]"),
  texts: (a) => (a && a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]"),
  date: (v) => (v ? `${q(v)}::date` : "null"),
  ts: (v) => (v ? `${q(v)}::timestamptz` : "null"),
  /** Monthly or daily dates: "2027-12" -> 2027-12-01. */
  month: (v) => (v ? `${q(v.length === 7 ? `${v}-01` : v)}::date` : "null"),
  /** Multi-row insert; `rows` are arrays of already-quoted literals. */
  insert(table, cols, rows) {
    if (!rows.length) return `-- ${table}: no rows\n`;
    const body = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
    return `insert into ${table} (${cols.join(", ")}) values\n${body};\n`;
  },
};

export function migrationNames() {
  if (!existsSync(MIGRATIONS)) return [];
  return readdirSync(MIGRATIONS).filter((f) => f.endsWith(".sql"));
}

export async function loadSeedmaps() {
  const dir = join(PKG, "seedmap");
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".mjs"))
    .sort();
  const maps = [];
  for (const f of files) {
    const m = await import(pathToFileURL(join(dir, f)).href);
    maps.push({ file: f, ...m });
  }
  return maps;
}

const canonicalCache = new Map();
function loadCanonical(name) {
  if (!canonicalCache.has(name))
    canonicalCache.set(
      name,
      JSON.parse(readFileSync(join(PKG, "canonical", `${name}.json`), "utf8")),
    );
  return canonicalCache.get(name);
}

/** Returns { "<output>.sql": content } for every seedmap. */
export async function buildSeed({ all = false, migrations = migrationNames() } = {}) {
  const maps = await loadSeedmaps();
  const out = {};
  for (const m of maps) {
    const missing = (m.requires ?? []).filter(
      (marker) => !migrations.some((f) => f.includes(marker)),
    );
    const header = [
      `-- ${m.output}: generated by packages/fixtures/scripts/build-seed.mjs from seedmap/${m.file}.`,
      "-- Do not edit. Facts: DESIGN.md §5/§5b via packages/fixtures/canonical. Regenerate: npm run -w @plinth/fixtures gen",
      `-- requires migrations matching: ${(m.requires ?? []).join(", ") || "(none)"}`,
    ];
    if (missing.length && !all) {
      out[m.output] =
        `${header.join("\n")}\n-- SKIPPED: no migration in supabase/migrations matches ${missing.join(", ")}. Rerun the generator once it lands.\n`;
      continue;
    }
    const body = m.build({ load: loadCanonical, sql });
    const digest = createHash("sha256").update(body).digest("hex").slice(0, 16);
    out[m.output] =
      `${header.join("\n")}\n-- content sha256 (first 16): ${digest}\n\nbegin;\n\n${body}\ncommit;\n`;
  }
  return out;
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const all = args.includes("--all");
  const outIdx = args.indexOf("--out");
  const outDir = outIdx >= 0 ? resolve(args[outIdx + 1]) : SEED_DIR;
  const files = await buildSeed({ all });
  const changed = Object.entries(files).filter(
    ([f, c]) => !existsSync(join(outDir, f)) || readFileSync(join(outDir, f), "utf8") !== c,
  );
  if (check) {
    for (const [f] of changed) console.log(`drift: ${relative(ROOT, join(outDir, f))}`);
    console.log(
      `build-seed --check: ${Object.keys(files).length} files, ${changed.length} changed`,
    );
    process.exit(changed.length ? 1 : 0);
  }
  mkdirSync(outDir, { recursive: true });
  for (const [f, c] of changed) writeFileSync(join(outDir, f), c);
  const skipped = Object.values(files).filter((c) => c.includes("-- SKIPPED:")).length;
  console.log(
    `build-seed: ${Object.keys(files).length} files (${skipped} skipped for missing migrations), ${changed.length} written to ${relative(ROOT, outDir) || "."}`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
