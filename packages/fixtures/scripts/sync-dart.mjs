#!/usr/bin/env node
// Copies packages/fixtures/{expected,vectors}/**/*.json into the Flutter package
// packages/fixtures/dart (assets/), lists every asset folder in its pubspec.yaml and writes
// lib/src/fixture_index.dart (the keys per function), so the app's FIXTURES mode reads the
// very same files as the web.
//
//   node scripts/sync-dart.mjs          # write
//   node scripts/sync-dart.mjs --check  # exit 1 on drift
//
// Owner: T03. The media/ images are not copied (the app bundles its own images).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DART = join(PKG, "dart");
const SOURCES = ["expected", "vectors"];

function jsonFiles(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...jsonFiles(p));
    else if (e.name.endsWith(".json")) out.push(p);
  }
  return out;
}

export function plan() {
  const files = {};
  const assetDirs = new Set();
  const index = {};
  for (const src of SOURCES)
    for (const abs of jsonFiles(join(PKG, src))) {
      const rel = relative(PKG, abs);
      files[join("assets", rel)] = readFileSync(abs, "utf8");
      assetDirs.add(`assets/${dirname(rel)}/`);
      const [top, fn, file] = rel.split("/");
      if (top === "expected" && file && !file.startsWith("_"))
        (index[fn] ??= []).push(file.replace(/\.json$/, ""));
    }
  const vectors = jsonFiles(join(PKG, "vectors")).map((p) =>
    relative(join(PKG, "vectors"), p).replace(/\.json$/, ""),
  );
  const dirs = [...assetDirs].sort();
  files["pubspec.yaml"] = `name: plinth_fixtures
description: "Plinth fixture JSON (packages/fixtures/expected and vectors) bundled as Flutter assets for FIXTURES mode. Generated by packages/fixtures/scripts/sync-dart.mjs."
version: 0.0.1
publish_to: 'none'

environment:
  sdk: ^3.13.4
  flutter: ">=3.47.0"

dependencies:
  flutter:
    sdk: flutter

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^6.0.0

# The asset list below is generated by packages/fixtures/scripts/sync-dart.mjs. Do not edit.
flutter:
  assets:
${dirs.map((d) => `    - ${d}`).join("\n")}
`;
  const q = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
  files["lib/src/fixture_index.dart"] =
    `// GENERATED by packages/fixtures/scripts/sync-dart.mjs. Do not edit.

/// Fixture keys for each API read function: \`assets/expected/<function>/<key>.json\`.
const Map<String, List<String>> plinthExpectedKeys = <String, List<String>>{
${Object.keys(index)
  .sort()
  .map((fn) => `  ${q(fn)}: <String>[\n${index[fn].map((k) => `    ${q(k)},`).join("\n")}\n  ],`)
  .join("\n")}
};

/// Golden vectors: \`assets/vectors/<name>.json\`.
const List<String> plinthVectorNames = <String>[
${vectors.map((v) => `  ${q(v)},`).join("\n")}
];
`;
  return files;
}

function main() {
  const check = process.argv.includes("--check");
  const files = plan();
  const existing = jsonFiles(join(DART, "assets")).map((p) => relative(DART, p));
  const stale = existing.filter((p) => !(p in files));
  const changed = Object.entries(files).filter(
    ([p, c]) => !existsSync(join(DART, p)) || readFileSync(join(DART, p), "utf8") !== c,
  );
  if (check) {
    for (const [p] of changed) console.log(`drift: dart/${p}`);
    for (const p of stale) console.log(`stale: dart/${p}`);
    console.log(
      `sync-dart --check: ${Object.keys(files).length} files, ${changed.length} changed, ${stale.length} stale`,
    );
    process.exit(changed.length || stale.length ? 1 : 0);
  }
  for (const p of stale) rmSync(join(DART, p));
  for (const [p, c] of changed) {
    mkdirSync(dirname(join(DART, p)), { recursive: true });
    writeFileSync(join(DART, p), c);
  }
  console.log(
    `sync-dart: ${Object.keys(files).length} files, ${changed.length} written, ${stale.length} removed`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
